package jp.bsb.diagnostics;

/**
 * 診断（エラーや警告）が発生した処理系内部の「フェーズ（処理段階）」を表す列挙型です。
 *
 * <p>【コンピュータ科学の観点】 プログラミング言語の処理系は、ソースコードをいくつもの独立した段階（パイプライン）を経て処理します。
 * 各フェーズで発見された問題は、この列挙型によってどの段階で発生したかが識別されます。
 *
 * <p>また、この列挙型の宣言順（{@code ordinal()} 順）は、複数のエラーをソートして ユーザーへ報告する際の優先順位としても機能します（上流の段階のエラーほど先に表示されます）。
 */
public enum DiagnosticStage {
  /** 1. ソースコード読取り・UTF-8文字エンコーディング検証段階（ファイルサイズ超過、不正なバイト列など） */
  UTF8,

  /** 2. 字句解析（Lexical Analysis）段階（無効な文字、数値リテラルの不正、識別子の命名規則違反など） */
  LEXICAL,

  /** 3. 構文解析（Syntax Analysis / Parsing）段階（文法違反、括弧の不一致、単語定義の構文エラーなど） */
  SYNTAX,

  /** 4. 名前解決（Name Resolution）段階（未定義の単語呼出し、名前の重複定義、予約語の再定義など） */
  NAME,

  /** 5. 静的型、スタック効果、制御フロー検査段階（スタックのアンダーフロー、経路合流の不一致など） */
  TYPE_AND_STACK,

  /** 6. 中間表現（IR: Intermediate Representation）生成段階（命令数の上限超過など） */
  IR,

  /** 7. 実行時（Runtime）段階（呼出スタックあふれ、命令数上限、実行タイムアウトなど） */
  RUNTIME
}
