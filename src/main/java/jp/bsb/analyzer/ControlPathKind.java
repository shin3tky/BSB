package jp.bsb.analyzer;

/**
 * 文の解析後に、制御がどこへ進むかを表します。
 *
 * <p>【コンピュータ科学の観点：制御フロー】通常の処理は次の文へ流れますが、復帰・脱出・継続は別の場所へ飛びます。これらを区別して保持すると、
 * 実行されない後続コードを検出し、分岐やループの正しい出口だけを合流できます。
 */
public enum ControlPathKind {
  /** 次の文へ到達する通常経路です。 */
  FALLTHROUGH,

  /** 「戻る」によって現在の単語から復帰する経路です。 */
  RETURNED,

  /** プログラム指定終了によって呼出し元へ戻らない経路です。 */
  TERMINATED,

  /** 「打ち切る」によって最内側のループから脱出する経路です。 */
  BROKEN,

  /** 「続ける」によって最内側のループの次回へ進む経路です。 */
  CONTINUED
}
